import { test, expect, openVideo, addBridge, readProject } from './fixtures';

for (const width of [1440, 390]) test(`one generation timeline aligns references, image guides and masks at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  let submissions = 0; await page.route('**/api/comfy/interstitials', route => { submissions++; return route.abort(); });
  await openVideo(page); await addBridge(page);
  await page.getByRole('button', { name: 'Expand generation timeline', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Generation timeline', exact: true });
  await expect(editor).toBeVisible();
  const start = editor.getByRole('button', { name: 'Start reference: interstitial-reference.mp4', exact: true });
  const end = editor.getByRole('button', { name: 'End reference: interstitial-reference.mp4', exact: true });
  await expect(start).toBeVisible(); await expect(end).toBeVisible();
  await expect(editor.getByRole('button', { name: 'Edit video mask', exact: true })).toBeVisible();
  await expect(editor.getByRole('button', { name: 'Edit audio mask', exact: true })).toBeVisible();
  const ruler = editor.locator('.generation-time-ruler'), box = (await ruler.boundingBox())!;
  await ruler.click({ position: { x: box.width * .45, y: 10 } });
  const cursor = Number(await editor.getByRole('slider', { name: 'Generation timeline playhead' }).inputValue());
  await editor.getByRole('button', { name: 'Add image keyframe', exact: true }).click();
  await expect(editor.getByLabel('Keyframe frame', { exact: true })).toHaveValue(String(cursor));
  await expect.poll(async () => (await readProject(page)).interstitials[0].keyframes[0].frame).toBe(cursor - 39);
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 240; canvas.height = 140;
    const context = canvas.getContext('2d')!; context.fillStyle = '#568486'; context.fillRect(0, 0, 240, 140);
    context.fillStyle = '#e6be8f'; context.fillRect(90, 25, 50, 90); return canvas.toDataURL('image/png').split(',')[1];
  });
  await editor.getByLabel('Upload Keyframe image', { exact: true }).setInputFiles({ name: 'pose.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await expect(editor.getByRole('group', { name: 'Keyframe image', exact: true })).toHaveAttribute('aria-busy', 'false');
  await editor.locator('.video-keyframes').getByRole('button', { name: 'Preview pose.png', exact: true }).click();
  const preview = page.getByRole('dialog', { name: 'Preview pose.png', exact: true });
  await expect(preview.locator('img')).toBeVisible(); await page.keyboard.press('Escape');
  await expect(preview).toHaveCount(0); await expect(editor).toBeVisible();
  await editor.getByLabel('Keyframe time in seconds', { exact: true }).fill('3.625');
  await expect(editor.getByLabel('Keyframe frame', { exact: true })).toHaveValue('87');
  await editor.getByLabel('Keyframe frame', { exact: true }).press('Enter'); expect(submissions).toBe(0);
  const marker = editor.getByRole('button', { name: 'Select image keyframe 1', exact: true });
  await marker.scrollIntoViewIfNeeded();
  const lane = (await editor.locator('.generation-guides-lane').boundingBox())!, point = (await marker.boundingBox())!;
  await page.mouse.move(point.x + point.width / 2, point.y + point.height / 2); await page.mouse.down();
  await page.mouse.move(point.x + point.width / 2 + lane.width * 24 / 226, point.y + point.height / 2, { steps: 5 }); await page.mouse.up();
  await expect(editor.getByLabel('Keyframe frame', { exact: true })).toHaveValue('111');
  await editor.getByRole('button', { name: 'Close generation timeline', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByLabel('Keyframe frame', { exact: true })).toHaveValue('87');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(page.getByLabel('Keyframe frame', { exact: true })).toHaveValue('111');
  await page.getByRole('button', { name: 'Expand generation timeline', exact: true }).click();
  await start.click();
  await expect(editor.locator('.generation-selected-reference')).toContainText('Source 0.375–2s');
  await editor.getByRole('group', { name: 'Start reference', exact: true }).getByRole('button', { name: 'None', exact: true }).click();
  await expect(start).toHaveCount(0);
  await marker.click();
  await expect(editor.getByLabel('Keyframe frame', { exact: true })).toHaveValue('72');
  await expect(editor.getByLabel('Keyframe time in seconds', { exact: true })).toHaveValue('3');
  await editor.getByLabel('Generation timeline zoom', { exact: true }).selectOption('2');
  expect(await editor.locator('.generation-timeline-scroll').evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true);
  await editor.getByLabel('Generation timeline zoom', { exact: true }).selectOption('1');
  await editor.getByRole('button', { name: 'Edit audio mask', exact: true }).click();
  await expect(editor.getByRole('group', { name: 'Reference and generated footage', exact: true })).toBeVisible();
  await expect(editor.getByRole('button', { name: 'Select image keyframe 1', exact: true })).toBeVisible();
  const path = editor.locator('.generation-mask-lane').last().locator('path'), original = await path.getAttribute('d');
  await editor.getByRole('button', { name: 'Add keyframe', exact: true }).click();
  await editor.getByLabel('Keyframe regeneration', { exact: true }).fill('35');
  await expect(path).not.toHaveAttribute('d', original!);
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(editor).toBeVisible(); await expect(path).toHaveAttribute('d', original!);
  await editor.getByRole('button', { name: 'Edit video mask', exact: true }).click();
  await editor.getByRole('button', { name: 'Add keyframe', exact: true }).click();
  await editor.getByLabel('Keyframe regeneration', { exact: true }).fill('45');
  await editor.getByRole('button', { name: 'Apply video mask', exact: true }).click();
  await expect.poll(async () => (await readProject(page)).interstitials[0].videoMaskCurve?.end.some((point: { strength: number }) => point.strength === .45)).toBe(true);
  await editor.locator('.generation-timeline-heading').scrollIntoViewIfNeeded();
  await page.screenshot({ path: `test-results/generation-timeline-${width}.png` });
  expect(await editor.locator('.generation-timeline-editor').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await marker.focus(); await marker.press('Delete');
  await expect(marker).toHaveCount(0);
  await expect.poll(async () => (await readProject(page)).interstitials[0].keyframes ?? []).toEqual([]);
  await editor.getByRole('button', { name: 'Close generation timeline', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select image keyframe 1', exact: true })).toBeVisible();
  expect(errors).toEqual([]); expect(submissions).toBe(0);
});
